"""Checked-in source-schema descriptors and the activation preflight.

The grow archive capture may only move or delete source observations after a
preflight proves that the live database still matches the checked-in
descriptors in ``source_schema.json``. The repository DDL is the authority
for those descriptors (production is never queried to build them), so any
drift -- a new column, a changed type, a different key, a lost hypertable or
an optional stream that suddenly exists without a lossless descriptor --
blocks activation and export until the descriptor is deliberately updated.

Blocking is intentionally conservative:

* a missing core stream (measurement / automation / setpoint / photoperiod /
  relay) blocks;
* a missing optional historical stream is recorded explicitly as absent;
* an unavailable stream (no repository DDL exists) is recorded absent, but
  blocks the moment the relation actually exists because its shape is
  unknown;
* an unknown or missing column, a type/nullability change, a column-order
  change, a primary-key or unique-constraint change or a hypertable-status
  change blocks.

The module has no import side effects beyond reading its catalog file on
demand and talks to PostgreSQL through an existing asyncpg connection or
pool.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final, Mapping, Sequence

import asyncpg

CATALOG_FORMAT: Final = "sj-cea-source-schema/1"
DEFAULT_CATALOG_PATH: Final = Path(__file__).with_name("source_schema.json")
PUBLIC_SCHEMA: Final = "public"

STREAM_STATUS_DEFINED: Final = "defined"
STREAM_STATUS_UNAVAILABLE: Final = "unavailable"

#: Stable ``generation`` vocabulary the checked-in descriptors may use.
#: ``identity_always`` covers ``GENERATED ALWAYS AS IDENTITY`` key handlers,
#: ``identity_default`` covers ``GENERATED BY DEFAULT AS IDENTITY`` and
#: ``serial``/``bigserial`` cover the sequence-backed identity-like key
#: columns of the observed schema.
VALID_GENERATIONS: Final = frozenset(
    {"serial", "bigserial", "identity_always", "identity_default"}
)

PREFLIGHT_STATUS_OK: Final = "ok"
PREFLIGHT_STATUS_ABSENT: Final = "absent"
PREFLIGHT_STATUS_DRIFT: Final = "drift"

#: Fixed, non-secret blocking codes. Every code is stable across releases so
#: operators can grep a blocked preflight report and the activation log.
SCHEMA_CATALOG_INVALID: Final = "schema_catalog_invalid"
SCHEMA_TIMESCALEDB_MISSING: Final = "schema_timescaledb_missing"
SCHEMA_TIMESCALEDB_VERSION_UNSUPPORTED: Final = "schema_timescaledb_version_unsupported"
SCHEMA_CORE_STREAM_MISSING: Final = "schema_core_stream_missing"
SCHEMA_DESCRIPTOR_UNAVAILABLE: Final = "schema_descriptor_unavailable"
SCHEMA_RELATION_KIND_MISMATCH: Final = "schema_relation_kind_mismatch"
SCHEMA_UNKNOWN_COLUMN: Final = "schema_unknown_column"
SCHEMA_MISSING_COLUMN: Final = "schema_missing_column"
SCHEMA_COLUMN_ORDER_CHANGED: Final = "schema_column_order_changed"
SCHEMA_TYPE_MISMATCH: Final = "schema_type_mismatch"
SCHEMA_NULLABILITY_MISMATCH: Final = "schema_nullability_mismatch"
SCHEMA_PRIMARY_KEY_MISMATCH: Final = "schema_primary_key_mismatch"
SCHEMA_UNIQUE_CONSTRAINT_MISMATCH: Final = "schema_unique_constraint_mismatch"
SCHEMA_GENERATION_MISMATCH: Final = "schema_generation_mismatch"
SCHEMA_HYPERTABLE_MISMATCH: Final = "schema_hypertable_mismatch"

BLOCKING_CODES: Final = frozenset({
    SCHEMA_CATALOG_INVALID,
    SCHEMA_TIMESCALEDB_MISSING,
    SCHEMA_TIMESCALEDB_VERSION_UNSUPPORTED,
    SCHEMA_CORE_STREAM_MISSING,
    SCHEMA_DESCRIPTOR_UNAVAILABLE,
    SCHEMA_RELATION_KIND_MISMATCH,
    SCHEMA_UNKNOWN_COLUMN,
    SCHEMA_MISSING_COLUMN,
    SCHEMA_COLUMN_ORDER_CHANGED,
    SCHEMA_TYPE_MISMATCH,
    SCHEMA_NULLABILITY_MISMATCH,
    SCHEMA_PRIMARY_KEY_MISMATCH,
    SCHEMA_UNIQUE_CONSTRAINT_MISMATCH,
    SCHEMA_GENERATION_MISMATCH,
    SCHEMA_HYPERTABLE_MISMATCH,
})


class SourceCatalogError(Exception):
    """The checked-in catalog file is missing, malformed or self-inconsistent."""

    code: Final = SCHEMA_CATALOG_INVALID

    def __init__(self, detail: str) -> None:
        self.detail = detail
        super().__init__(f"{self.code}: {detail}")


@dataclass(frozen=True, slots=True)
class SourceColumn:
    """One ordered source column; the fingerprint compares these three facts."""

    name: str
    type: str
    not_null: bool
    generation: str | None = None


@dataclass(frozen=True, slots=True)
class SourceStream:
    """One plan observation stream and its checked-in descriptor."""

    name: str
    status: str
    core: bool
    relation: str | None
    time_column: str | None
    stable_ordering: tuple[str, ...]
    ownership_mode: str | None
    ownership_detail: str | None
    default_record_role: str | None
    hypertable: bool | None
    chunk_interval: str | None
    columns: tuple[SourceColumn, ...]
    primary_key: tuple[str, ...]
    unique_constraints: tuple[tuple[str, ...], ...]
    fingerprint: str | None
    notes: str | None
    #: Verified alternate primary keys (ordered column tuples). The baseline
    #: DDL of a hypertable source can be impossible to apply (a non-time
    #: primary key cannot coexist with the partitioning column); the checked-in
    #: variant is the exact disposable verified shape, and any other live shape
    #: still blocks.
    primary_key_variants: tuple[tuple[str, ...], ...] = ()

@dataclass(frozen=True, slots=True)
class SourceCatalog:
    """The validated checked-in descriptor catalog."""

    format: str
    timescaledb_minimum_version: str
    streams: tuple[SourceStream, ...]
    catalog_fingerprint: str

    def by_name(self) -> Mapping[str, SourceStream]:
        return {stream.name: stream for stream in self.streams}

    def defined_streams(self) -> tuple[SourceStream, ...]:
        return tuple(stream for stream in self.streams if stream.status == STREAM_STATUS_DEFINED)


@dataclass(frozen=True, slots=True)
class SchemaFinding:
    """One blocking observation, always carrying its fixed code."""

    code: str
    stream: str
    detail: str

    def as_dict(self) -> dict[str, str]:
        return {"code": self.code, "stream": self.stream, "detail": self.detail}


@dataclass(frozen=True, slots=True)
class StreamPreflight:
    """Per-stream result; ``absent`` optional streams are recorded, not blocked."""

    name: str
    core: bool
    status: str
    findings: tuple[SchemaFinding, ...]

    def as_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "core": self.core,
            "status": self.status,
            "findings": [finding.as_dict() for finding in self.findings],
        }


@dataclass(frozen=True, slots=True)
class SchemaPreflightReport:
    """The complete preflight result for one live database."""

    ok: bool
    timescaledb_version: str | None
    streams: tuple[StreamPreflight, ...]
    findings: tuple[SchemaFinding, ...]
    blocked_codes: tuple[str, ...]

    def stream(self, name: str) -> StreamPreflight:
        for result in self.streams:
            if result.name == name:
                return result
        raise KeyError(name)

    def as_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "timescaledb_version": self.timescaledb_version,
            "blocked_codes": list(self.blocked_codes),
            "findings": [finding.as_dict() for finding in self.findings],
            "streams": [stream.as_dict() for stream in self.streams],
        }


class SchemaPreflightBlocked(Exception):
    """Raised by :func:`assert_schema_preflight` when the live schema drifts."""

    code: Final = "schema_preflight_blocked"

    def __init__(self, report: SchemaPreflightReport) -> None:
        self.report = report
        super().__init__(f"{self.code}: {', '.join(report.blocked_codes) or 'unknown'}")


def _column_payload(column: SourceColumn) -> list[Any]:
    return [column.name, column.type, column.not_null, column.generation]


def stream_fingerprint(stream: SourceStream) -> str:
    """Canonical sha256 over the ordered lossless facts of one stream."""

    payload = {
        "relation": stream.relation,
        "columns": [_column_payload(column) for column in stream.columns],
        "primary_key": list(stream.primary_key),
        "primary_key_variants": [list(variant) for variant in stream.primary_key_variants],
        "unique_constraints": [list(constraint) for constraint in stream.unique_constraints],
        "hypertable": stream.hypertable,
    }
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()


def catalog_fingerprint(streams: Sequence[SourceStream]) -> str:
    """Canonical sha256 over the per-stream fingerprints in catalog order."""

    canonical = json.dumps(
        [[stream.name, stream.fingerprint] for stream in streams],
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()


def _require(raw: Mapping[str, Any], key: str, kind: type, where: str) -> Any:
    if key not in raw:
        raise SourceCatalogError(f"{where}: missing key {key!r}")
    value = raw[key]
    if not isinstance(value, kind):
        raise SourceCatalogError(f"{where}: key {key!r} must be {kind.__name__}")
    return value


def _parse_stream(raw: Mapping[str, Any]) -> SourceStream:
    if not isinstance(raw, Mapping):
        raise SourceCatalogError("stream entries must be objects")
    name = _require(raw, "name", str, "stream")
    where = f"stream {name}"
    status = _require(raw, "status", str, where)
    if status not in (STREAM_STATUS_DEFINED, STREAM_STATUS_UNAVAILABLE):
        raise SourceCatalogError(f"{where}: unknown status {status!r}")
    core = _require(raw, "core", bool, where)
    fingerprint = raw.get("fingerprint")
    notes = raw.get("notes")
    if status == STREAM_STATUS_UNAVAILABLE:
        if fingerprint is not None:
            raise SourceCatalogError(f"{where}: unavailable streams must not carry a fingerprint")
        return SourceStream(
            name=name,
            status=status,
            core=core,
            relation=None,
            time_column=None,
            stable_ordering=(),
            ownership_mode=None,
            ownership_detail=None,
            default_record_role=None,
            hypertable=None,
            chunk_interval=None,
            columns=(),
            primary_key=(),
            unique_constraints=(),
            fingerprint=None,
            notes=notes,
        )

    relation = _require(raw, "relation", str, where)
    if not relation.startswith(f"{PUBLIC_SCHEMA}."):
        raise SourceCatalogError(f"{where}: relation must live in schema {PUBLIC_SCHEMA}")
    columns_raw = _require(raw, "columns", list, where)
    if not columns_raw:
        raise SourceCatalogError(f"{where}: defined streams need at least one column")
    columns: list[SourceColumn] = []
    for column_raw in columns_raw:
        if not isinstance(column_raw, Mapping):
            raise SourceCatalogError(f"{where}: column entries must be objects")
        generation = column_raw.get("generation")
        if generation is not None and generation not in VALID_GENERATIONS:
            raise SourceCatalogError(
                f"{where}: column {column_raw.get('name')!r} generation must be one of {sorted(VALID_GENERATIONS)}"
            )
        column = SourceColumn(
            name=_require(column_raw, "name", str, where),
            type=_require(column_raw, "type", str, where),
            not_null=_require(column_raw, "not_null", bool, where),
            generation=generation or None,
        )
        if not column.name or not column.type:
            raise SourceCatalogError(f"{where}: column name/type must be non-empty")
        columns.append(column)
    if len({column.name for column in columns}) != len(columns):
        raise SourceCatalogError(f"{where}: duplicate column names")
    primary_key = tuple(_require(raw, "primary_key", list, where))
    variants_raw = raw.get("primary_key_variants")
    if variants_raw is None:
        variants_raw = []
    if not isinstance(variants_raw, list):
        raise SourceCatalogError(f"{where}: primary_key_variants must be a list")
    variants: list[tuple[str, ...]] = []
    column_names = {column.name for column in columns}
    time_column = raw.get("time_column")
    for variant in variants_raw:
        if not isinstance(variant, list) or not all(isinstance(name, str) for name in variant):
            raise SourceCatalogError(f"{where}: primary-key variants must be string lists")
        unknown_columns = set(variant) - column_names
        if unknown_columns:
            raise SourceCatalogError(f"{where}: variant {variant!r} names unknown columns {sorted(unknown_columns)}")
        if set(variant) == set(primary_key):
            raise SourceCatalogError(f"{where}: variant {variant!r} duplicates the baseline primary key")
        if not set(primary_key) <= set(variant):
            raise SourceCatalogError(f"{where}: variant {variant!r} must extend the baseline primary key")
        if time_column is not None and time_column not in variant:
            raise SourceCatalogError(
                f"{where}: variant {variant!r} must include the observation time column {time_column!r}"
            )
        variants.append(tuple(variant))
    unique_raw = _require(raw, "unique_constraints", list, where)
    unique_constraints = tuple(tuple(constraint) for constraint in unique_raw)
    ownership = raw.get("ownership") or {}
    if not isinstance(ownership, Mapping):
        raise SourceCatalogError(f"{where}: ownership must be an object")
    hypertable = _require(raw, "hypertable", bool, where)
    stream = SourceStream(
        name=name,
        status=status,
        core=core,
        relation=relation,
        time_column=raw.get("time_column"),
        stable_ordering=tuple(raw.get("stable_ordering") or ()),
        ownership_mode=ownership.get("mode"),
        ownership_detail=ownership.get("detail"),
        default_record_role=raw.get("default_record_role"),
        hypertable=hypertable,
        chunk_interval=raw.get("chunk_interval"),
        columns=tuple(columns),
        primary_key=primary_key,
        unique_constraints=unique_constraints,
        fingerprint=fingerprint,
        notes=notes,
        primary_key_variants=tuple(variants),
    )
    expected = stream_fingerprint(stream)
    if fingerprint != expected:
        raise SourceCatalogError(
            f"{where}: fingerprint {fingerprint!r} does not match the descriptor content ({expected})"
        )
    return stream


def load_source_catalog(path: Path | None = None) -> SourceCatalog:
    """Load and fully validate the checked-in descriptor catalog."""

    catalog_path = path or DEFAULT_CATALOG_PATH
    try:
        raw_text = catalog_path.read_text(encoding="utf-8")
    except OSError as error:
        raise SourceCatalogError(f"cannot read {catalog_path}: {error}") from error
    try:
        document = json.loads(raw_text)
    except json.JSONDecodeError as error:
        raise SourceCatalogError(f"{catalog_path} is not valid JSON: {error}") from error
    if not isinstance(document, Mapping):
        raise SourceCatalogError(f"{catalog_path}: top level must be an object")
    if document.get("format") != CATALOG_FORMAT:
        raise SourceCatalogError(f"{catalog_path}: unsupported format {document.get('format')!r}")
    timescaledb = document.get("timescaledb")
    if not isinstance(timescaledb, Mapping) or not isinstance(timescaledb.get("minimum_version"), str):
        raise SourceCatalogError(f"{catalog_path}: timescaledb.minimum_version is required")
    streams_raw = document.get("streams")
    if not isinstance(streams_raw, list) or not streams_raw:
        raise SourceCatalogError(f"{catalog_path}: streams must be a non-empty list")
    streams = tuple(_parse_stream(stream_raw) for stream_raw in streams_raw)
    names = [stream.name for stream in streams]
    if len(set(names)) != len(names):
        raise SourceCatalogError(f"{catalog_path}: duplicate stream names")
    expected_catalog = catalog_fingerprint(streams)
    if document.get("catalog_fingerprint") != expected_catalog:
        raise SourceCatalogError(
            f"{catalog_path}: catalog_fingerprint does not match the descriptor content ({expected_catalog})"
        )
    return SourceCatalog(
        format=document["format"],
        timescaledb_minimum_version=timescaledb["minimum_version"],
        streams=streams,
        catalog_fingerprint=expected_catalog,
    )


def _version_tuple(text: str) -> tuple[int, ...]:
    parts = re.findall(r"\d+", text)
    if not parts:
        return ()
    return tuple(int(part) for part in parts[:3])


def _version_supported(actual: str, minimum: str) -> bool:
    actual_tuple = _version_tuple(actual)
    minimum_tuple = _version_tuple(minimum)
    if not actual_tuple or not minimum_tuple:
        return False
    width = max(len(actual_tuple), len(minimum_tuple))
    actual_padded = actual_tuple + (0,) * (width - len(actual_tuple))
    minimum_padded = minimum_tuple + (0,) * (width - len(minimum_tuple))
    return actual_padded >= minimum_padded


async def _relation_oid(conn: asyncpg.Connection, relation: str) -> tuple[int, str] | None:
    schema, _, name = relation.partition(".")
    row = await conn.fetchrow(
        "SELECT c.oid, c.relkind::text AS relkind FROM pg_catalog.pg_class c "
        "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = $1 AND c.relname = $2",
        schema,
        name,
    )
    if row is None:
        return None
    return int(row["oid"]), str(row["relkind"])


async def _relation_exists(conn: asyncpg.Connection, relation: str) -> bool:
    schema, _, name = relation.partition(".")
    return (
        await conn.fetchval(
            "SELECT to_regclass($1) IS NOT NULL", f"{schema}.{name}"
        )
    ) is True


async def _live_columns(conn: asyncpg.Connection, oid: int) -> list[tuple[str, str, bool, str, int]]:
    rows = await conn.fetch(
        "SELECT a.attname, "
        "pg_catalog.format_type(a.atttypid, a.atttypmod) AS formatted_type, "
        "a.attnotnull, a.attidentity::text AS attidentity, a.attnum "
        "FROM pg_catalog.pg_attribute a "
        "WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped "
        "ORDER BY a.attnum",
        oid,
    )
    return [
        (
            str(row["attname"]),
            str(row["formatted_type"]),
            bool(row["attnotnull"]),
            str(row["attidentity"] or ""),
            int(row["attnum"]),
        )
        for row in rows
    ]


async def _sequence_default_attnums(conn: asyncpg.Connection, oid: int) -> set[int]:
    rows = await conn.fetch(
        "SELECT adnum FROM pg_catalog.pg_attrdef "
        "WHERE adrelid = $1 AND pg_catalog.pg_get_expr(adbin, adrelid) LIKE 'nextval(%'",
        oid,
    )
    return {int(row["adnum"]) for row in rows}


def _classify_generation(attidentity: str, sequence_default: bool, formatted_type: str) -> str | None:
    """Map catalog internals onto the checked-in ``generation`` tokens."""

    if attidentity == "a":
        return "identity_always"
    if attidentity == "d":
        return "identity_default"
    if sequence_default and formatted_type == "integer":
        return "serial"
    if sequence_default and formatted_type == "bigint":
        return "bigserial"
    return None


async def _live_keys(conn: asyncpg.Connection, oid: int) -> tuple[tuple[str, ...], tuple[tuple[str, ...], ...]]:
    columns = await conn.fetch(
        "SELECT attnum, attname FROM pg_catalog.pg_attribute "
        "WHERE attrelid = $1 AND attnum > 0 AND NOT attisdropped",
        oid,
    )
    names = {int(row["attnum"]): str(row["attname"]) for row in columns}
    rows = await conn.fetch(
        "SELECT contype::text AS contype, conkey FROM pg_catalog.pg_constraint "
        "WHERE conrelid = $1 AND contype IN ('p', 'u')",
        oid,
    )
    primary_key: tuple[str, ...] = ()
    unique: list[tuple[str, ...]] = []
    for row in rows:
        key = tuple(names[int(attnum)] for attnum in row["conkey"] if int(attnum) in names)
        if row["contype"] == "p":
            primary_key = key
        else:
            unique.append(key)
    return primary_key, tuple(sorted(unique))


async def _is_hypertable(conn: asyncpg.Connection, relation: str) -> bool:
    schema, _, name = relation.partition(".")
    return (
        await conn.fetchval(
            "SELECT EXISTS (SELECT 1 FROM timescaledb_information.hypertables "
            "WHERE hypertable_schema = $1 AND hypertable_name = $2)",
            schema,
            name,
        )
    ) is True


async def _inspect_stream(conn: asyncpg.Connection, stream: SourceStream, *, timescaledb_present: bool) -> StreamPreflight:
    findings: list[SchemaFinding] = []

    def finding(code: str, detail: str) -> None:
        findings.append(SchemaFinding(code=code, stream=stream.name, detail=detail))

    if stream.status == STREAM_STATUS_UNAVAILABLE:
        assert stream.relation is None
        relation = f"{PUBLIC_SCHEMA}.{stream.name}"
        if await _relation_exists(conn, relation):
            finding(
                SCHEMA_DESCRIPTOR_UNAVAILABLE,
                f"{relation} exists but no repository definition describes it losslessly",
            )
            return StreamPreflight(stream.name, stream.core, PREFLIGHT_STATUS_DRIFT, tuple(findings))
        return StreamPreflight(stream.name, stream.core, PREFLIGHT_STATUS_ABSENT, ())

    assert stream.relation is not None
    relation = await _relation_oid(conn, stream.relation)
    if relation is None:
        if stream.core:
            finding(SCHEMA_CORE_STREAM_MISSING, f"core relation {stream.relation} is absent")
            return StreamPreflight(stream.name, stream.core, PREFLIGHT_STATUS_DRIFT, tuple(findings))
        return StreamPreflight(stream.name, stream.core, PREFLIGHT_STATUS_ABSENT, ())

    oid, relkind = relation
    if relkind != "r":
        finding(SCHEMA_RELATION_KIND_MISMATCH, f"{stream.relation} has relkind {relkind!r}, expected an ordinary table")
        return StreamPreflight(stream.name, stream.core, PREFLIGHT_STATUS_DRIFT, tuple(findings))

    live_columns = await _live_columns(conn, oid)
    live_names = [column[0] for column in live_columns]
    expected_names = [column.name for column in stream.columns]
    expected_set = set(expected_names)
    live_set = set(live_names)

    for column in stream.columns:
        if column.name not in live_set:
            finding(SCHEMA_MISSING_COLUMN, f"column {column.name!r} is missing")
    for name in live_names:
        if name not in expected_set:
            finding(SCHEMA_UNKNOWN_COLUMN, f"column {name!r} is not in the checked-in descriptor")
    if not findings and live_names != expected_names:
        finding(
            SCHEMA_COLUMN_ORDER_CHANGED,
            f"column order changed: descriptor {expected_names!r} vs live {live_names!r}",
        )

    live_by_name = {column[0]: column for column in live_columns}
    sequence_defaults = await _sequence_default_attnums(conn, oid)
    for column in stream.columns:
        live = live_by_name.get(column.name)
        if live is None:
            continue
        if live[1] != column.type:
            finding(SCHEMA_TYPE_MISMATCH, f"column {column.name!r} is {live[1]!r}, descriptor says {column.type!r}")
        if live[2] != column.not_null:
            finding(
                SCHEMA_NULLABILITY_MISMATCH,
                f"column {column.name!r} not_null is {live[2]}, descriptor says {column.not_null}",
            )
        live_generation = _classify_generation(live[3], live[4] in sequence_defaults, live[1])
        if live_generation != column.generation:
            finding(
                SCHEMA_GENERATION_MISMATCH,
                f"column {column.name!r} generation is {live_generation!r}, descriptor says {column.generation!r}",
            )

    live_primary_key, live_unique = await _live_keys(conn, oid)
    expected_unique = tuple(sorted(stream.unique_constraints))
    if live_primary_key != stream.primary_key and live_primary_key not in stream.primary_key_variants:
        accepted = [stream.primary_key, *stream.primary_key_variants]
        finding(
            SCHEMA_PRIMARY_KEY_MISMATCH,
            f"primary key {list(live_primary_key)!r}, descriptor accepts "
            f"{[list(item) for item in accepted]!r}",
        )
    if live_unique != expected_unique:
        finding(
            SCHEMA_UNIQUE_CONSTRAINT_MISMATCH,
            f"unique constraints {[list(item) for item in live_unique]!r}, "
            f"descriptor says {[list(item) for item in expected_unique]!r}",
        )

    if timescaledb_present:
        hypertable = await _is_hypertable(conn, stream.relation)
        if stream.hypertable and not hypertable:
            finding(SCHEMA_HYPERTABLE_MISMATCH, f"{stream.relation} is no longer a hypertable")
        elif not stream.hypertable and hypertable:
            finding(SCHEMA_HYPERTABLE_MISMATCH, f"{stream.relation} unexpectedly became a hypertable")

    status = PREFLIGHT_STATUS_DRIFT if findings else PREFLIGHT_STATUS_OK
    return StreamPreflight(stream.name, stream.core, status, tuple(findings))


async def run_schema_preflight(
    conn: asyncpg.Connection,
    *,
    catalog: SourceCatalog | None = None,
) -> SchemaPreflightReport:
    """Compare the live source schema against the checked-in descriptors."""

    resolved = catalog or load_source_catalog()
    findings: list[SchemaFinding] = []

    timescaledb_version = await conn.fetchval(
        "SELECT extversion FROM pg_catalog.pg_extension WHERE extname = 'timescaledb'"
    )
    if timescaledb_version is None:
        findings.append(
            SchemaFinding(
                code=SCHEMA_TIMESCALEDB_MISSING,
                stream="<extension>",
                detail="TimescaleDB is not installed in this database",
            )
        )
    elif not _version_supported(str(timescaledb_version), resolved.timescaledb_minimum_version):
        findings.append(
            SchemaFinding(
                code=SCHEMA_TIMESCALEDB_VERSION_UNSUPPORTED,
                stream="<extension>",
                detail=(
                    f"TimescaleDB {timescaledb_version} is below the checked-in minimum "
                    f"{resolved.timescaledb_minimum_version}"
                ),
            )
        )

    stream_results: list[StreamPreflight] = []
    for stream in resolved.streams:
        result = await _inspect_stream(conn, stream, timescaledb_present=timescaledb_version is not None)
        stream_results.append(result)
        findings.extend(result.findings)

    blocked_codes = tuple(sorted({finding.code for finding in findings if finding.code in BLOCKING_CODES}))
    return SchemaPreflightReport(
        ok=not blocked_codes,
        timescaledb_version=str(timescaledb_version) if timescaledb_version is not None else None,
        streams=tuple(stream_results),
        findings=tuple(findings),
        blocked_codes=blocked_codes,
    )


async def assert_schema_preflight(
    conn: asyncpg.Connection,
    *,
    catalog: SourceCatalog | None = None,
) -> SchemaPreflightReport:
    """Run the preflight and raise :class:`SchemaPreflightBlocked` on drift."""

    report = await run_schema_preflight(conn, catalog=catalog)
    if not report.ok:
        raise SchemaPreflightBlocked(report)
    return report


async def _run_cli(args: argparse.Namespace) -> int:
    try:
        catalog = load_source_catalog(args.catalog)
    except SourceCatalogError as error:
        print(str(error), file=sys.stderr)
        return 2
    connection = await asyncpg.connect(args.database_url)
    try:
        report = await run_schema_preflight(connection, catalog=catalog)
    finally:
        await connection.close()
    if args.as_json:
        print(json.dumps(report.as_dict(), indent=2))
    else:
        state = "ok" if report.ok else "blocked"
        print(f"source schema preflight {state} (timescaledb {report.timescaledb_version})")
        for stream in report.streams:
            print(f"  {stream.name}: {stream.status}")
        for finding in report.findings:
            print(f"  {finding.code} [{finding.stream}] {finding.detail}", file=sys.stderr)
    return 0 if report.ok else 1


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m grow_archive_service.schema",
        description="Compare a live database against the checked-in source-schema descriptors.",
    )
    parser.add_argument("--database-url", required=True, help="PostgreSQL DSN of the database to inspect")
    parser.add_argument("--catalog", type=Path, default=None, help="alternate source_schema.json path")
    parser.add_argument("--json", action="store_true", dest="as_json", help="print the full report as JSON")
    return asyncio.run(_run_cli(parser.parse_args(argv)))


if __name__ == "__main__":
    raise SystemExit(main())
